#!/usr/bin/env node
/**
 * dsh-ollama-credits — build.mjs
 *
 * Deterministic bundler for both halves (CONTRACT.md §2). No dependencies.
 *
 *  - HOST half: `src/host/index.js` is copied verbatim to `lib/index.js` under a
 *    generated-file banner. It is authored, not transformed.
 *  - CLIENT half: `src/client/*.js` are concatenated in filename order into a
 *    single lazy-CJS browser module at `lib/client.js`:
 *
 *        window.__ModuleLoader__.load({ id: 'dsh-ollama-credits', factory: (require) => { ... } });
 *
 *    Each source file is a plain statement list valid inside a function body: no
 *    import/export, no JSX, no top-level return. Modules share the `NS` object.
 *
 * Usage:
 *   node build.mjs              # write lib/
 *   node build.mjs --check      # exit 1 when lib/ is not current
 *   node build.mjs --quiet      # suppress the success line
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** Bundle identity — CONTRACT.md §2 fixes the module id. */
export const MODULE_ID = "dsh-ollama-credits";
/** The client source holding `apply`/`inject` (CONTRACT.md §5.1). */
export const REQUIRED_CLIENT_MODULE = "90-entry.js";

const here = dirname(fileURLToPath(import.meta.url));

const HOST_SOURCE = join(here, "src/host/index.js");
const HOST_OUTPUT = join(here, "lib/index.js");
const CLIENT_DIR = join(here, "src/client");
const CLIENT_OUTPUT = join(here, "lib/client.js");

const BANNER = (what, from) =>
  [
    "/**",
    ` * dsh-ollama-credits — ${what}.`,
    " *",
    " * GENERATED FILE — do not edit.",
    ` * Generated by build.mjs from ${from} (CONTRACT.md §2).`,
    ` * Edit the source and rebuild with \`node build.mjs\`.`,
    " */",
    "",
  ].join("\n");

const OPEN = [
  "window.__ModuleLoader__.load({",
  `  id: '${MODULE_ID}',`,
  "  factory: (require) => {",
  "    var module = { exports: {} };",
  "    var exports = module.exports;",
  "    Object.defineProperty(exports, Symbol.toStringTag, { value: 'Module' });",
  "    var react = require('react');",
  "    var jsxRuntime = require('react/jsx-runtime');",
  "    var reactDomClient = null;",
  "    try { reactDomClient = require('react-dom/client'); } catch (error) { reactDomClient = null; }",
  "    var NS = { react: react, jsx: jsxRuntime.jsx, jsxs: jsxRuntime.jsxs, Fragment: react.Fragment, createRoot: reactDomClient === null ? null : reactDomClient.createRoot };",
].join("\n");

const CLOSE = ["    return module.exports;", "  }", "});", ""].join("\n");

/** Client module filenames in build order (numeric prefix ordering). */
export function clientModules() {
  if (!existsSync(CLIENT_DIR)) return [];
  return readdirSync(CLIENT_DIR)
    .filter((name) => name.endsWith(".js"))
    .sort((left, right) => left.localeCompare(right, "en"));
}

/** Render the client bundle text without touching the filesystem. */
export function renderClient() {
  const modules = clientModules();
  const missing = !modules.includes(REQUIRED_CLIENT_MODULE);
  const parts = [BANNER("CLIENT half", "src/client/*.js"), OPEN];
  for (const name of modules) {
    parts.push(`    //#region src/client/${name}`);
    parts.push(readFileSync(join(CLIENT_DIR, name), "utf8").replace(/\s*$/, ""));
    parts.push(`    //#endregion`);
  }
  parts.push(CLOSE);
  return { text: parts.join("\n"), modules, missing };
}

/** Render the host file text without touching the filesystem. */
export function renderHost() {
  const source = readFileSync(HOST_SOURCE, "utf8").replace(/\s*$/, "");
  return `${BANNER("HOST half", "src/host/index.js")}${source}\n`;
}

function write(path, text) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
}

function current(path, text) {
  return existsSync(path) && readFileSync(path, "utf8") === text;
}

/**
 * Run the CLI and return its exit code. Importing this module never touches the
 * filesystem: only the entry-point guard below calls this.
 * @param argv - CLI arguments without the interpreter and script path.
 * @returns the process exit code.
 */
export function main(argv = process.argv.slice(2)) {
  const flags = new Set(argv);
  const check = flags.has("--check");
  const quiet = flags.has("--quiet");

  const host = renderHost();
  const client = renderClient();

  if (client.missing) {
    console.error(`build.mjs: src/client/${REQUIRED_CLIENT_MODULE} is required (CONTRACT.md §5.1)`);
    return 1;
  }

  const stale = [];
  if (!current(HOST_OUTPUT, host)) stale.push("lib/index.js");
  if (!current(CLIENT_OUTPUT, client.text)) stale.push("lib/client.js");

  if (check) {
    if (stale.length > 0) {
      console.error(`build.mjs: stale output: ${stale.join(", ")}`);
      return 1;
    }
    if (!quiet) console.log(`build.mjs: lib/ is current (${client.modules.length} client modules)`);
    return 0;
  }

  write(HOST_OUTPUT, host);
  write(CLIENT_OUTPUT, client.text);
  if (!quiet) console.log(`build.mjs: wrote lib/index.js, lib/client.js (${client.modules.length} client modules)`);
  return 0;
}

const isEntryPoint = process.argv[1] !== undefined
  && resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isEntryPoint) process.exit(main());
